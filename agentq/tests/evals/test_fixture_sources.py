"""Fixture-source contracts for the smoke suite.

Builders author decision inputs; judgment drafts carry reviewer aliases; the
suite manifest records the baseline checkpoint and the exact profiles. The
miniature repository fixture is generated by a standalone script that must be
idempotent, refuse to overwrite changed source, and keep its own Git root with
no evaluation labels inside it.

Draft extension: an optional ``irrelevant_aliases`` list records evidence the
reviewer judged non-creditable. Such aliases must resolve to real variants and
must not appear in any witness.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

import pytest

from agentq.inspection.contracts import ResolvedTarget
from agentq.inspection.features import extract_features
from agentq.inspection.scoring import DEFAULT_SCORING, score_evidence
from agentq.inspection.selection import DEFAULT_SELECTION, select_evidence
from evals.fixtures.synthetic import builders

PROJECT = Path(__file__).resolve().parents[2]
SUITE_PATH = PROJECT / "evals/suites/smoke-v1.json"
JUDGMENT_DIR = PROJECT / "evals/fixtures/synthetic/judgments"
SEED_SCRIPT = PROJECT / "scripts/create_m2_seed_repository.py"
REPOSITORY_FIXTURE = PROJECT / "evals/fixtures/repositories/orders_python/repository"
BASELINE_COMMIT = "fc80d7a4f1fc14c63e680014bcd2b25b03f813b3"
FIXTURE_FILES = (
    "pyproject.toml",
    ".gitignore",
    "orders.py",
    "report.py",
    "legacy.py",
    "tests/__init__.py",
    "tests/test_orders.py",
)


def _suite() -> dict[str, Any]:
    return json.loads(SUITE_PATH.read_text(encoding="utf-8"))


def _draft(case_id: str) -> dict[str, Any]:
    path = JUDGMENT_DIR / f"{case_id}.json"
    return json.loads(path.read_text(encoding="utf-8"))


def _run_seed(project: Path) -> subprocess.CompletedProcess[str]:
    script = project / "scripts/create_m2_seed_repository.py"
    return subprocess.run(
        [sys.executable, str(script)],
        cwd=project,
        capture_output=True,
        text=True,
        check=False,
    )


def _tree_bytes(root: Path) -> dict[str, bytes]:
    return {
        str(path.relative_to(root)): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file() and ".git" not in path.relative_to(root).parts
    }


@pytest.fixture()
def seeded_project(tmp_path: Path) -> Path:
    if shutil.which("git") is None:
        pytest.skip("git is required to isolate the fixture checkout")
    project = tmp_path / "agentq"
    script = project / "scripts/create_m2_seed_repository.py"
    script.parent.mkdir(parents=True)
    shutil.copy2(SEED_SCRIPT, script)
    return project


def test_suite_lists_each_synthetic_case_with_its_sources() -> None:
    suite = _suite()
    assert suite["schema"] == "agentq.eval.suite/v1"
    assert suite["suite_id"] == "smoke-v1"
    cases = suite["cases"]
    assert [case["case_id"] for case in cases] == list(builders.BUILDERS)
    for case in cases:
        assert case["kind"] == "synthetic"
        assert case["capture_id"] is None
        builder_module, builder_name = case["builder"].split(":")
        assert builder_module == "evals.fixtures.synthetic.builders"
        assert callable(getattr(builders, builder_name))
        assert (PROJECT / case["judgment"]).is_file()
        assert _draft(case["case_id"])["case_id"] == case["case_id"]


def test_suite_records_the_baseline_checkpoint_and_profiles() -> None:
    config = _suite()["decision_config"]
    assert config["scoring"] == DEFAULT_SCORING.to_wire()
    assert config["selection"] == DEFAULT_SELECTION.to_wire()
    assert config["delivery_ceilings_chars"] == [6000, 12000, 24000]
    assert config["primary_delivery_chars"] == 12000
    baseline = _suite()["baseline"]
    assert baseline["commit"] == BASELINE_COMMIT
    assert len(baseline["commit"]) == 40


def test_every_builder_produces_a_consistent_source_level_fixture() -> None:
    for case_id, build in builders.BUILDERS.items():
        fixture = build()
        assert fixture.case_id == case_id
        assert fixture.pool.request_id == f"fixture-{case_id}"
        assert isinstance(fixture.resolution, ResolvedTarget)
        assert fixture.resolution.target == fixture.request.target
        assert fixture.policy.intent is fixture.request.intent
        assert fixture.budget.envelope_chars < fixture.budget.max_chars
        assert fixture.audit_note
        observations = {
            observation.observation_id for observation in fixture.pool.observations
        }
        for variant in fixture.pool.variants:
            assert variant.observation_id in observations
        acquisitions = {
            record.acquisition_id for record in fixture.pool.acquisitions
        }
        for observation in fixture.pool.observations:
            assert observation.acquisition_id in acquisitions
        assert fixture.variant_aliases
        assert len(set(fixture.variant_aliases)) == len(fixture.variant_aliases)
        assert set(fixture.variant_aliases.values()) <= {
            variant.variant_id for variant in fixture.pool.variants
        }


def test_every_builder_runs_through_the_current_scorer_and_selector() -> None:
    for build in builders.BUILDERS.values():
        fixture = build()
        features = extract_features(fixture.pool)
        assert len(features) == len(fixture.pool.observations)
        scores = score_evidence(
            features, DEFAULT_SCORING, intent=fixture.request.intent
        )
        assert len(scores) == len(features)
        first = select_evidence(fixture.pool, scores, fixture.policy, fixture.budget)
        second = select_evidence(fixture.pool, scores, fixture.policy, fixture.budget)
        assert first == second
        assert first.measured_cost <= fixture.budget.available_chars()


def test_judgment_drafts_use_only_known_aliases() -> None:
    for case_id, build in builders.BUILDERS.items():
        fixture = build()
        draft = _draft(case_id)
        assert draft["schema"] == "agentq.eval.judgment-draft/v1"
        assert draft["basis"] == "target_intent"
        assert draft["review_status"] == "reviewed"
        witnesses = {
            item["witness_id"]: item["acceptable_aliases"]
            for item in draft["witnesses"]
        }
        assert len(witnesses) == len(draft["witnesses"])
        assert draft["facets"]
        for facet in draft["facets"]:
            assert facet["facet_id"]
            assert isinstance(facet["critical"], bool)
            assert facet["audit_note"]
            assert facet["witness_sets"]
            for clause in facet["witness_sets"]:
                assert clause
                assert set(clause) <= set(witnesses)
        known = set(fixture.variant_aliases)
        for aliases in witnesses.values():
            assert set(aliases) <= known
        irrelevant = set(draft.get("irrelevant_aliases", []))
        assert irrelevant <= known
        credited = {alias for aliases in witnesses.values() for alias in aliases}
        assert not irrelevant.intersection(credited)


def test_repository_fixture_records_its_source_path_and_creation_method() -> None:
    entries = _suite()["repository_fixtures"]
    assert len(entries) == 1
    entry = entries[0]
    assert SEED_SCRIPT.is_file()
    assert entry["creation_method"].endswith("scripts/create_m2_seed_repository.py")
    source_root = PROJECT / entry["source_root"]
    assert source_root == REPOSITORY_FIXTURE
    for relative in FIXTURE_FILES:
        assert (source_root / relative).is_file()
    assert not (source_root / "cases.json").exists()
    assert entry["case_status"] == "pending"


def test_seed_script_generates_the_fixture_and_preserves_it_on_rerun(
    seeded_project: Path,
) -> None:
    first = _run_seed(seeded_project)
    assert first.returncode == 0, first.stderr
    assert "Ran 4 tests" in first.stderr
    assert "OK" in first.stderr
    fixture = (
        seeded_project / "evals/fixtures/repositories/orders_python/repository"
    )
    workspace = seeded_project.parent / ".agentq-eval/worktrees/orders-python"
    before = (_tree_bytes(fixture), _tree_bytes(workspace))
    second = _run_seed(seeded_project)
    assert second.returncode == 0, second.stderr
    assert (_tree_bytes(fixture), _tree_bytes(workspace)) == before


def test_seed_script_refuses_to_overwrite_changed_source(
    seeded_project: Path,
) -> None:
    assert _run_seed(seeded_project).returncode == 0
    changed = (
        seeded_project
        / "evals/fixtures/repositories/orders_python/repository/orders.py"
    )
    replacement = "def list_orders():\n    return []\n"
    changed.write_text(replacement, encoding="utf-8")
    result = _run_seed(seeded_project)
    assert result.returncode != 0
    assert "Refusing to overwrite changed fixture" in result.stderr
    assert changed.read_text(encoding="utf-8") == replacement


def test_seed_checkout_is_an_independent_git_root(seeded_project: Path) -> None:
    assert _run_seed(seeded_project).returncode == 0
    workspace = seeded_project.parent / ".agentq-eval/worktrees/orders-python"
    top = subprocess.check_output(
        ["git", "-C", str(workspace), "rev-parse", "--show-toplevel"], text=True
    ).strip()
    assert Path(top).resolve() == workspace.resolve()
    status = subprocess.check_output(
        ["git", "-C", str(workspace), "status", "--porcelain"], text=True
    )
    assert status == ""


def test_seed_checkout_carries_no_evaluation_labels(seeded_project: Path) -> None:
    assert _run_seed(seeded_project).returncode == 0
    workspace = seeded_project.parent / ".agentq-eval/worktrees/orders-python"
    files = {
        str(path.relative_to(workspace))
        for path in workspace.rglob("*")
        if path.is_file() and ".git" not in path.relative_to(workspace).parts
    }
    assert files == set(FIXTURE_FILES)
    assert not (workspace / "cases.json").exists()
    assert not (workspace / "judgments.json").exists()
